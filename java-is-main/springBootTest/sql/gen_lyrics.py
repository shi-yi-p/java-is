# 按 song_id 映射：从导出文件读 歌名 -> song_id（取第一个出现的 id）
def load_id_map(path):
    m = {}
    with io.open(path, 'r', encoding='utf-8', errors='ignore') as f:
        for line in f:
            line = line.rstrip('\n').rstrip('\r')
            if not line:
                continue
            parts = line.split('\t')
            if len(parts) < 2:
                continue
            sid = parts[0].strip()
            title = parts[1].strip()
            # 同名歌曲取第一个出现的 song_id
            if title and title not in m:
                m[title] = sid
    return m

def to_lrc(text, total_sec=240):
    """把纯文本歌词转成 LRC：每行加时间戳。"""
    lines = [l for l in text.split('\n') if l.strip()]
    n = len(lines)
    if n == 0:
        return ''
    lrc = []
    for i, line in enumerate(lines):
        # 均匀分配时间，末尾留白
        t = int(total_sec * i / n)
        mm = t // 60
        ss = t % 60
        lrc.append('[%02d:%02d.00]%s' % (mm, ss, line))
    return '\n'.join(lrc)

def main():
    idmap_path = sys.argv[1] if len(sys.argv) > 1 else 'hotsongs.txt'
    id_map = load_id_map(idmap_path)

    out_lines = []
    out_lines.append('-- 自动生成的原创歌词（LRC），写入 song.lyric')
    out_lines.append('USE shark_music;')
    out_lines.append('')

    written = 0
    missing = []
    for title, text in LYRICS.items():
        sid = id_map.get(title)
        if sid is None:
            missing.append(title)
            continue
        lrc = to_lrc(text)
        # 转义单引号
        lrc_esc = lrc.replace('\\', '\\\\').replace("'", "''")
        out_lines.append("UPDATE song SET lyric='%s' WHERE id=%s AND deleted=0;" % (lrc_esc, sid))
        written += 1

    out_lines.append('')
    out_lines.append("-- 共写入 %d 首歌词" % written)

    with io.open('gen_lyrics.sql', 'w', encoding='utf-8') as f:
        f.write('\n'.join(out_lines) + '\n')

    print('写入歌词数: %d' % written)
    print('缺失歌名: %s' % (', '.join(missing) if missing else '无'))

if __name__ == '__main__':
    main()
